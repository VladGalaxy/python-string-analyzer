# Описание: Программа принимает текст, анализирует его с помощью
# методов строк, делает срезы и шифрует текст простым сдвигом.
# ==========================================

# 1. Получаем данные от пользователя
user_input = input("Введите текст или пароль для анализа: ")

# Используем метод strip() для удаления случайных пробелов по краям
clean_text = user_input.strip()

# Проверяем, не ввел ли пользователь пустую строку
if clean_text == "":
    print("Ошибка: Вы ввели пустую строку!")
else:
    print("\n--- АНАЛИЗ СТРОКИ ---")
    
    # 2. Длина, индексация и срезы (Slices)
    print(f"Длина текста: {len(clean_text)} символов")
    print(f"Первый символ (индекс 0): {clean_text[0]}")
    print(f"Последний символ (индекс -1): {clean_text[-1]}")
    
    # Выводим текст наоборот (шаг -1) и каждый второй символ (шаг 2)
    print(f"Текст наоборот: {clean_text[::-1]}")
    print(f"Каждый второй символ: {clean_text[::2]}")
    
    # 3. Классификация символов (проверки)
    print("\n--- ПРОВЕРКИ (True/False) ---")
    print(f"Это только цифры? (.isdigit): {clean_text.isdigit()}")
    print(f"Это только буквы? (.isalpha): {clean_text.isalpha()}")
    print(f"Это буквы и цифры? (.isalnum): {clean_text.isalnum()}")
    print(f"Все буквы заглавные? (.isupper): {clean_text.isupper()}")
    
    # 4. Поиск и замена
    print("\n--- ПОИСК И ЗАМЕНА ---")
    # Приводим текст к нижнему регистру, чтобы найти все буквы 'а' (и большие, и маленькие)
    lower_text = clean_text.lower()
    count_a = lower_text.count("а")
    print(f"Количество букв 'а' в тексте: {count_a}")
    
    # Метод replace меняет все пробелы на нижние подчеркивания
    formatted_text = clean_text.replace(" ", "_")
    print(f"Текст без пробелов (через _): {formatted_text}")
    
    # 5. Работа с Unicode и шифрование (Шифр Цезаря)
    print("\n--- ШИФРОВАНИЕ (Сдвиг на 1 символ) ---")
    encrypted_text = ""
    
    # Перебираем каждый символ в строке
    for char in clean_text:
        # ord() получает числовой код символа, прибавляем 1 (сдвиг)
        # chr() превращает новый числовой код обратно в символ
        new_char = chr(ord(char) + 1)
        encrypted_text += new_char
        
    print(f"Зашифрованный текст: {encrypted_text}")
    
    # 6. Сравнение строк
    print("\n--- СРАВНЕНИЕ СТРОК ---")
    # Python сравнивает строки по кодам Unicode. 
    # Заглавные буквы всегда меньше строчных.
    if clean_text < "Python":
        print(f"Ваш текст ('{clean_text}') МЕНЬШЕ, чем слово 'Python'")
    else:
        print(f"Ваш текст ('{clean_text}') БОЛЬШЕ или РАВЕН слову 'Python'")

print("\nАнализ завершен! Спасибо за использование.")
